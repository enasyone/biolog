namespace Biolog.Features.ApiSecurity;

public enum ServiceAccountStatus
{
    Active,
    Revoked,
}

/// <summary>
/// BIO-INT-003-AC01: a tenant-scoped API service account. <see cref="Id"/> doubles as the
/// OAuth2 <c>client_id</c> - there is no separate "management id" vs "wire id", the same
/// single-identifier shape BIO-INT-001's <c>AuthProviderConfig.ProviderId</c> uses.
///
/// <see cref="SecretHash"/> is the ONLY form the client secret is ever stored in (BIO-INT-003-
/// AC04) - an HMAC-SHA256 digest of the secret under a server-side pepper
/// (<see cref="ApiSecretHasher"/>), never the plaintext. The plaintext is generated once per
/// create/rotate call, handed back to the caller in that one response, and never persisted,
/// logged, or re-derivable from <see cref="SecretHash"/> alone.
/// </summary>
public sealed record ServiceAccount(
    string Id,
    string TenantId,
    string DisplayName,
    IReadOnlySet<string> Scopes,
    ServiceAccountStatus Status,
    byte[] SecretHash,
    DateTimeOffset SecretLastRotatedAt,
    int Version,
    DateTimeOffset CreatedAt);

public sealed class ServiceAccountConcurrencyConflictException(int currentVersion)
    : Exception($"service account version conflict - current version is {currentVersion}")
{
    public int CurrentVersion { get; } = currentVersion;
}

/// <summary>
/// Tenant-scoped service account storage (BIO-INT-003-AC01). Every management method takes
/// <paramref name="tenantId"/> explicitly, same shape as BIO-INT-001's
/// <c>IAuthProviderConfigRepository</c> - this project has no ambient tenant concept of its own.
///
/// <see cref="GetAsync"/> returns <c>null</c> for an account that does not exist AND for one
/// that exists in a different tenant (ADR-0002 §4.3's "not found, never forbidden").
///
/// <see cref="GetByClientIdAsync"/> is the one deliberate exception: the OAuth2
/// client_credentials grant (<c>POST /api/v1/oauth/token</c>) authenticates a caller who does
/// not yet have a tenant context - the client_id/secret pair themselves are what reveal which
/// tenant the caller belongs to, the standard shape for a multi-tenant client-credentials
/// flow. No endpoint uses this method to bypass tenant scoping for anything management-shaped.
/// </summary>
public interface IServiceAccountRepository
{
    /// <summary><paramref name="id"/> is generated by the caller (BIO-INT-003-ZB-04) so it can
    /// be audited BEFORE this mutation runs - the point-of-no-return is this call, not the audit
    /// write that now precedes it.</summary>
    Task<ServiceAccount> CreateAsync(string tenantId, string id, string displayName, IReadOnlySet<string> scopes, byte[] secretHash, CancellationToken cancellationToken);

    Task<ServiceAccount?> GetAsync(string tenantId, string id, CancellationToken cancellationToken);

    Task<ServiceAccount?> GetByClientIdAsync(string clientId, CancellationToken cancellationToken);

    Task<IReadOnlyList<ServiceAccount>> ListAsync(string tenantId, CancellationToken cancellationToken);

    /// <summary>Throws <see cref="ServiceAccountConcurrencyConflictException"/> if the stored
    /// version does not match <paramref name="expectedVersion"/>. Returns <c>null</c> for an
    /// account the tenant cannot see.</summary>
    Task<ServiceAccount?> UpdateSecretHashAsync(string tenantId, string id, byte[] newSecretHash, int expectedVersion, CancellationToken cancellationToken);

    /// <summary>Throws <see cref="ServiceAccountConcurrencyConflictException"/> if the stored
    /// version does not match <paramref name="expectedVersion"/>. Returns <c>null</c> for an
    /// account the tenant cannot see.</summary>
    Task<ServiceAccount?> RevokeAsync(string tenantId, string id, int expectedVersion, CancellationToken cancellationToken);
}

public sealed class InMemoryServiceAccountRepository : IServiceAccountRepository
{
    private readonly Dictionary<string, ServiceAccount> _accountsById = [];
    private readonly Lock _gate = new();

    public Task<ServiceAccount> CreateAsync(string tenantId, string id, string displayName, IReadOnlySet<string> scopes, byte[] secretHash, CancellationToken cancellationToken)
    {
        var now = DateTimeOffset.UtcNow;
        var account = new ServiceAccount(
            Id: id,
            TenantId: tenantId,
            DisplayName: displayName,
            Scopes: scopes,
            Status: ServiceAccountStatus.Active,
            SecretHash: secretHash,
            SecretLastRotatedAt: now,
            Version: 1,
            CreatedAt: now);

        lock (_gate)
        {
            _accountsById[account.Id] = account;
        }

        return Task.FromResult(account);
    }

    public Task<ServiceAccount?> GetAsync(string tenantId, string id, CancellationToken cancellationToken)
    {
        lock (_gate)
        {
            return Task.FromResult(
                _accountsById.TryGetValue(id, out var account) && account.TenantId == tenantId ? account : null);
        }
    }

    public Task<ServiceAccount?> GetByClientIdAsync(string clientId, CancellationToken cancellationToken)
    {
        lock (_gate)
        {
            return Task.FromResult(_accountsById.GetValueOrDefault(clientId));
        }
    }

    public Task<IReadOnlyList<ServiceAccount>> ListAsync(string tenantId, CancellationToken cancellationToken)
    {
        lock (_gate)
        {
            IReadOnlyList<ServiceAccount> result = _accountsById.Values.Where(a => a.TenantId == tenantId).ToList();
            return Task.FromResult(result);
        }
    }

    public Task<ServiceAccount?> UpdateSecretHashAsync(string tenantId, string id, byte[] newSecretHash, int expectedVersion, CancellationToken cancellationToken)
    {
        lock (_gate)
        {
            if (!_accountsById.TryGetValue(id, out var current) || current.TenantId != tenantId)
            {
                return Task.FromResult<ServiceAccount?>(null);
            }

            if (current.Version != expectedVersion)
            {
                throw new ServiceAccountConcurrencyConflictException(current.Version);
            }

            var updated = current with
            {
                SecretHash = newSecretHash,
                SecretLastRotatedAt = DateTimeOffset.UtcNow,
                Version = current.Version + 1,
            };
            _accountsById[id] = updated;
            return Task.FromResult<ServiceAccount?>(updated);
        }
    }

    public Task<ServiceAccount?> RevokeAsync(string tenantId, string id, int expectedVersion, CancellationToken cancellationToken)
    {
        lock (_gate)
        {
            if (!_accountsById.TryGetValue(id, out var current) || current.TenantId != tenantId)
            {
                return Task.FromResult<ServiceAccount?>(null);
            }

            if (current.Version != expectedVersion)
            {
                throw new ServiceAccountConcurrencyConflictException(current.Version);
            }

            var updated = current with { Status = ServiceAccountStatus.Revoked, Version = current.Version + 1 };
            _accountsById[id] = updated;
            return Task.FromResult<ServiceAccount?>(updated);
        }
    }
}
